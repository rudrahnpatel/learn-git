// Regenerates the precache list and cache version inside sw.js.
//   node tools/precache.mjs
// Run it after ANY change to a shipped file (js, css, fonts, index.html, icons, manifest). The cache
// version is a hash of every precached file's bytes, so a changed file always yields a new version,
// which makes the browser see a new sw.js, install it, and show the "Update available" toast.
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, relative, dirname, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const walk = (dir) => readdirSync(dir).flatMap((n) => {
  const p = join(dir, n);
  return statSync(p).isDirectory() ? walk(p) : [p];
});

const files = [
  'index.html', 'manifest.webmanifest',
  ...walk(join(root, 'css')), ...walk(join(root, 'js')), ...walk(join(root, 'fonts')).filter((f) => f.endsWith('.woff2')),
  ...walk(join(root, 'icons')).filter((f) => /icon-(192|512|maskable-512)\.png$|apple-touch/.test(f)),
  // the pre-rendered 3D reward chest (tools/chest3d): two stills and the opening strip, ~100 KB together
  ...walk(join(root, 'icons', 'chest')).filter((f) => f.endsWith('.webp')),
].map((f) => (f.startsWith(root) ? relative(root, f) : f).split(sep).join('/'));
const list = [...new Set(files)].sort();

const hash = createHash('sha256');
for (const f of list) { hash.update(f); hash.update(readFileSync(join(root, f))); }
const version = hash.digest('hex').slice(0, 10);

const swPath = join(root, 'sw.js');
const sw = readFileSync(swPath, 'utf8');
const block = `/* >>> precache (generated by tools/precache.mjs, do not edit) */
const VERSION = '${version}';
const PRECACHE = ${JSON.stringify(list, null, 2)};
/* <<< precache */`;
const next = sw.replace(/\/\* >>> precache[\s\S]*?\/\* <<< precache \*\//, block);
if (next === sw) { console.log(`sw.js already at ${version} (${list.length} files)`); }
else { writeFileSync(swPath, next); console.log(`sw.js -> ${version}, ${list.length} files precached`); }
